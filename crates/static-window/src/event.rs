//! What the window system reports, one label per kind: an app compiles
//! programs only for the kinds it handles. Each event is also delivered to
//! its window entity, so a behavior can `cx.on::<CloseRequested>(window)`.
use static_ecs::prelude::*;

use crate::input::{Key, KeyCode, Modifiers, MouseButton};
use crate::window::Surface;

macro_rules! payload {
    ($($t:ty),* $(,)?) => {
        $(impl Schedule for $t {
            type In = Ref<Self>;
        })*
    };
}

/// Once per wakeup that does work, after the events: the app's update (and
/// where behaviors are polled: `behavior::<B, _>(Step)`). The timing is in
/// [`FrameTime`].
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct Step;
impl Schedule for Step {}

/// This wakeup's timing: a resource, set before [`Step`].
#[derive(Clone, Copy, Debug, Default, PartialEq)]
pub struct FrameTime {
    /// CLOCK_MONOTONIC nanoseconds, now.
    pub now_ns: u64,
    /// When this wakeup's frames are predicted to reach the screen, or 0
    /// before the first presentation report.
    pub display_ns: u64,
    /// Seconds since the previous step, from display times when known (so
    /// animation moves as far as the screen shows it), else the wall clock.
    /// After an idle stretch it includes the idle time: clamp it if that
    /// matters.
    pub dt: f32,
}

/// A window needs pixels: draw it into its framebuffer.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Redraw {
    pub window: Entity,
}

/// The user asked to close the window (the title bar's ×, a shortcut).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct CloseRequested {
    pub window: Entity,
}
/// The window's logical size or scale changed (not sent for the first
/// configure).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Resized {
    pub window: Entity,
    pub surface: Surface,
}
/// The window gained or lost keyboard focus.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct FocusChanged {
    pub window: Entity,
    pub focused: bool,
}
/// The pointer moved to `(x, y)` in the window, in logical units (also
/// sent when it enters).
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct PointerMoved {
    pub window: Entity,
    pub x: f32,
    pub y: f32,
}
/// The pointer left the window.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct PointerLeft {
    pub window: Entity,
}
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct PointerButton {
    pub window: Entity,
    pub button: MouseButton,
    pub pressed: bool,
}
/// Raw, unaccelerated pointer motion while the window holds the pointer
/// with [`PointerLock`](crate::PointerLock).
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct PointerDelta {
    pub window: Entity,
    pub dx: f32,
    pub dy: f32,
}
/// Wheel or touchpad scroll, in logical units, positive down and right.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Scroll {
    pub window: Entity,
    pub dx: f32,
    pub dy: f32,
    /// For a wheel: detents turned (fractions on high-resolution wheels).
    pub lines: Option<(f32, f32)>,
}
/// A key went down, up, or repeated.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct KeyInput {
    pub window: Entity,
    pub code: KeyCode,
    pub key: Key,
    pub pressed: bool,
    /// Generated by holding the key.
    pub repeat: bool,
    /// After this key.
    pub modifiers: Modifiers,
}
/// Text the user typed: insertable text only, never control characters
/// (Backspace, Enter, Tab are keys).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct TextInput {
    pub window: Entity,
    text: InlineText,
}
impl TextInput {
    pub(crate) fn new(window: Entity, text: &str) -> Option<Self> {
        Some(Self { window, text: InlineText::new(text)? })
    }
    pub fn text(&self) -> &str {
        self.text.as_str()
    }
}

payload!(Redraw, CloseRequested, Resized, FocusChanged, PointerMoved, PointerLeft, PointerButton, PointerDelta, Scroll, KeyInput, TextInput);

/// Up to 32 bytes of UTF-8 inline, so a keystroke allocates nothing.
#[derive(Clone, Copy, PartialEq, Eq)]
struct InlineText {
    bytes: [u8; 32],
    len: u8,
}
impl InlineText {
    fn new(text: &str) -> Option<Self> {
        let mut bytes = [0; 32];
        bytes.get_mut(..text.len())?.copy_from_slice(text.as_bytes());
        Some(Self { bytes, len: text.len() as u8 })
    }
    fn as_str(&self) -> &str {
        // SAFETY: copied from a `&str`, whole.
        unsafe { std::str::from_utf8_unchecked(&self.bytes[..self.len as usize]) }
    }
}
impl std::fmt::Debug for InlineText {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        self.as_str().fmt(f)
    }
}

/// Whether `text` is insertable (no control characters), so a key press
/// that produced one is reported as a key only.
pub(crate) fn insertable(text: &str) -> bool {
    !text.is_empty() && !text.chars().any(char::is_control)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn text_is_inline_up_to_32_bytes() {
        assert_eq!(InlineText::new("é").unwrap().as_str(), "é");
        assert!(InlineText::new(&"x".repeat(32)).is_some());
        assert!(InlineText::new(&"x".repeat(33)).is_none());
        assert!(insertable("a\u{301}"));
        assert!(!insertable("\u{8}") && !insertable("\r") && !insertable("\u{7f}") && !insertable(""));
    }
}
